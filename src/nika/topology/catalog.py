ZOO_TOPOLOGY_NAMES: tuple[str, ...] = tuple(
    sorted(name for names in ZOO_TOPOLOGY_TIERS.values() for name in names)
)

_overlap = set(SNDLIB_TOPOLOGY_NAMES) & set(ZOO_TOPOLOGY_NAMES)
if _overlap:
    raise RuntimeError(f"SNDlib and Topology Zoo names overlap: {sorted(_overlap)}")
del _overlap

ISP_TOPOLOGY_NAMES: tuple[str, ...] = SNDLIB_TOPOLOGY_NAMES + ZOO_TOPOLOGY_NAMES

_SNDLIB_SUFFIX = ".xml"
_ZOO_SUFFIX = ".graphml"


def topology_data_root() -> Path:
    """Return the directory that holds the vendored topology files."""
    return Path(__file__).resolve().parents[1] / "net_env" / "isp" / "topologies"


def topology_path(name: str) -> Path:
    suffix = _ZOO_SUFFIX if name in ZOO_TOPOLOGY_NAMES else _SNDLIB_SUFFIX
    return topology_data_root() / f"{name}{suffix}"


def list_topologies() -> list[str]:
    """Return sorted names of the vendored topology files."""
    return sorted(
        path.stem
        for path in topology_data_root().iterdir()
        if path.suffix in (_SNDLIB_SUFFIX, _ZOO_SUFFIX)
    )


def is_zoo_topology(topology: str | Path) -> bool:
    if isinstance(topology, Path):
        return topology.suffix == _ZOO_SUFFIX
    return topology in ZOO_TOPOLOGY_NAMES or topology.endswith(_ZOO_SUFFIX)


def _parse_topology(path: Path, name: str) -> NetworkTopology:
    if path.suffix == _ZOO_SUFFIX:
        return parse_zoo_graphml(path, name=name)
    return parse_sndlib_xml(path, name=name)


@cache
def _load_catalog_topology(name: str) -> NetworkTopology:
    return _parse_topology(topology_path(name), name)


def load_topology(name_or_path: str | Path) -> NetworkTopology:
    """Load a vendored topology by catalog name, or parse an XML/GraphML path."""
    if isinstance(name_or_path, str) and name_or_path in ISP_TOPOLOGY_NAMES:
        return _load_catalog_topology(name_or_path)
    path = Path(name_or_path)
    if not path.is_file():
        raise SndlibUnsupportedError(
            f"unknown ISP topology {name_or_path!r}; "
            f"expected a catalog name or a {_SNDLIB_SUFFIX}/{_ZOO_SUFFIX} path"
        )
    name = path.parent.name if path.name == "network.xml" else path.stem
    return _parse_topology(path, name)


def isp_topology_size(name: str) -> str:
    """Return the relative s/m/l size tier of a vendored topology."""
    for tiers in (SNDLIB_TOPOLOGY_TIERS, ZOO_TOPOLOGY_TIERS):
        for topo_size, names in tiers.items():
            if name in names:
                return topo_size
    raise ValueError(f"Unknown ISP topology {name!r}.")
